"""Freeze the `emoeng` package into a stand-alone app and run it.

    python tools/build_release.py                # one-file bundle, then launch
    python tools/build_release.py --console      # keep a console next to the window
    python tools/build_release.py --no-run       # build only, don't launch

Works on Windows, Linux and macOS; the platform picks the exe suffix and
whether PyInstaller's `--windowed` flag means anything. Everything the
engine's own CLI accepts is baked into the frozen exe, because the entry
script just calls `emoeng.__main__.main`:

    MotionEngine                open the project manager
    MotionEngine editor <proj>  open the editor on a project
    MotionEngine run <proj>     play a project
    MotionEngine --run <proj>   same as run, the shortcut-friendly form
    MotionEngine build <proj>   freeze another project from inside the app

That last bit is what the "Create Shortcut" button in the manager leans
on: it writes a `.lnk` / `.desktop` / `.command` on the user's Desktop
that calls `<MotionEngine> --run <project>`.

Layout (one-file):

    emoeng/                      the package, analysed in place: its folder
                                  name is its import name, so the entry
                                  script's `from emoeng.__main__ import main`
                                  resolves for PyInstaller without staging
    tools/.build/                PyInstaller work files and the entry script
    tools/dist/MotionEngine.exe  the finished one-file bundle

On first run `engine.paths.projects_dir` copies the bundled
`emoeng/projects` beside the exe, so `projects/` appears after one launch
and the manager already has `demo` in it. The release packs copy `projects/`
and `docs/` beside the exe at build time, so a fresh unzip includes the
demo and offline manual immediately. The same thing happens wherever an
end-user unzips a copy of that folder.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
import tempfile
import time
import zipfile
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
REPO = TOOLS.parent

if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

# Single source of truth for the engine's identity. Bump `VERSION`, rename
# the frozen `ENGINE_NAME`, or edit the About dialog in `emoeng/const.py`
# and this tool picks it up on the next build.
from emoeng import const                      # noqa: E402
from emoeng.engine import prune               # noqa: E402
from emoeng.engine.build import BuildConfig   # noqa: E402
from emoeng.engine.loader import Project      # noqa: E402

# The package folder and the import name are the same thing, so the repo
# root is all PyInstaller needs on its search path.
SRC = REPO / const.NAME

ENGINE_NAME = const.ENGINE_NAME

BUILD = TOOLS / ".build"
DIST = TOOLS / "dist"

IS_WINDOWS = os.name == "nt"
IS_MACOS = sys.platform == "darwin"
IS_LINUX = sys.platform == "linux"
SEP = ";" if IS_WINDOWS else ":"


# ---------------------------------------------------------------- launcher
# `engine.build.BuildConfig` writes a game-only entry by default (it
# calls `engine.game.main`). We want the frozen app to be the whole
# engine - the same thing `python -m emoeng` runs - so we write our
# own entry file instead and hand it to PyInstaller directly.
ENGINE_ENTRY = f'''"""Generated by tools/build_release.py - the {ENGINE_NAME} app entry.

Boots the same dispatcher the source uses (`python -m emoeng`), so
every CLI form works on the frozen executable:

    {ENGINE_NAME}                   open the project manager
    {ENGINE_NAME} editor [project]  open the editor
    {ENGINE_NAME} run [project]     play a project
    {ENGINE_NAME} --run [project]   shortcut-friendly alias for `run`
    {ENGINE_NAME} build [project]   freeze another project
"""

import sys

from emoeng.__main__ import main


if __name__ == "__main__":
    raise SystemExit(main())
'''


# ------------------------------------------------------------------- utils
def log(msg, kind="info"):
    tag = {"info": "  ", "ok": " + ", "error": " ! "}.get(kind, "  ")
    print(f"{tag}{msg}", flush=True)


def exe_name():
    """The binary name on the current platform."""
    return f"{ENGINE_NAME}.exe" if IS_WINDOWS else ENGINE_NAME


def exe_path():
    if IS_WINDOWS:
        return DIST / f"{ENGINE_NAME}.exe"
    return DIST / ENGINE_NAME


# ------------------------------------------------------------------- entry
def write_entry() -> Path:
    entry = BUILD / f"{ENGINE_NAME}_entry.py"
    entry.parent.mkdir(parents=True, exist_ok=True)
    entry.write_text(ENGINE_ENTRY, encoding="utf-8")
    return entry


# ------------------------------------------------------------------- build
def make_config(console: bool) -> BuildConfig:
    """A BuildConfig pointed at this repo and its `emoeng` package.

    `prune.APP` matters: the default plan is a *game* plan, which drops the
    IDE and ships one project. Here the IDE is the product, so only the
    measured dead weight (an AVIF codec, numpy's Fortran generator) goes.
    """
    project = None
    default_project = (SRC / const.PROJECTS_DIRNAME / const.DEFAULT_PROJECT)
    if (default_project / const.MANIFEST_NAME).exists():
        project = Project(default_project)
    cfg = BuildConfig(project, mode=prune.APP)
    if project is not None:
        cfg.load(project)
    else:
        cfg.reset()
    cfg.set("name", ENGINE_NAME)
    cfg.set("distpath", str(DIST))
    cfg.set("workpath", str(BUILD))
    cfg.set("specpath", str(BUILD))
    cfg.set("onefile", True)
    # --windowed is only meaningful on Windows/macOS; on Linux PyInstaller
    # accepts it but it is a no-op, so always keep True unless --console.
    cfg.set("windowed", not console)
    cfg.set("clean", True)
    cfg.set("noconfirm", True)
    cfg.set("log_level", "INFO")
    cfg.set("paths", [str(REPO)])
    # NumPy's random extension imports this stdlib module dynamically.
    # PyInstaller's static scan misses it, but built-in texture generation
    # uses numpy.random when the frozen game starts.
    hidden = set(cfg.get("hidden_import") or ())
    hidden.add("secrets")
    cfg.set("hidden_import", sorted(hidden))
    # Bundle the whole `projects/` folder inside the frozen package so
    # `engine.paths.bundled_projects()` finds the demo on first run and
    # copies it beside the exe. The APP plan already points there; this is
    # the fallback for a checkout with no default project to scan.
    add_data = []
    bundled_dest = f"{const.NAME}/{const.PROJECTS_DIRNAME}"
    add_data.append(f"{SRC / const.PROJECTS_DIRNAME}{SEP}{bundled_dest}")
    # Also bundle the docs folder so it ships with the engine
    docs_src = REPO / "emoeng" / "docs"
    if docs_src.is_dir():
        docs_dest = f"{const.NAME}/docs"
        add_data.append(f"{docs_src}{SEP}{docs_dest}")
    # Bundle editor UI assets (icons, symbols) so they work in the frozen app
    app_ui_src = SRC / "editor" / "appUI"
    if app_ui_src.is_dir():
        app_ui_dest = f"{const.NAME}/editor/appUI"
        add_data.append(f"{app_ui_src}{SEP}{app_ui_dest}")
    # Bundle fonts so they work in the frozen app on all platforms
    fonts_src = SRC / "fonts"
    if fonts_src.is_dir():
        fonts_dest = f"{const.NAME}/fonts"
        add_data.append(f"{fonts_src}{SEP}{fonts_dest}")
    # Bundle the engine icon so it shows in the window/taskbar
    icon_src = SRC / const.ICON_NAME
    if icon_src.is_file():
        icon_dest = f"{const.NAME}"
        add_data.append(f"{icon_src}{SEP}{icon_dest}")
    cfg.set("add_data", add_data)
    return cfg


def run_build(cfg: BuildConfig, entry: Path) -> int:
    """Spawn PyInstaller with our entry and stream its output live."""
    if not cfg.available():
        log("PyInstaller is not installed: pip install pyinstaller", "error")
        return 2
    cmd = cfg.command(entry)
    try:
        proc = subprocess.Popen(cmd, cwd=str(TOOLS),
                                stdout=subprocess.PIPE,
                                stderr=subprocess.STDOUT,
                                text=True, bufsize=1)
    except OSError as exc:
        log(f"cannot start PyInstaller: {exc}", "error")
        return 1
    log(f"> {cfg.text(entry)}")
    for line in proc.stdout:
        log(line.rstrip())
    proc.stdout.close()
    code = proc.wait()
    if code != 0:
        log(f"PyInstaller exited {code}", "error")
    return code


# --------------------------------------------------------------------- run
def stage_projects():
    """Copy `emoeng/projects` beside the built exe.

    `engine.paths.projects_dir` takes a non-empty local `projects/`
    folder as-is, so the release zip already carries `demo` next to the
    exe and nobody has to launch the app once just to seed it."""
    src = SRC / const.PROJECTS_DIRNAME
    dest = DIST / const.PROJECTS_DIRNAME
    if not src.is_dir() or dest.exists():
        return
    try:
        shutil.copytree(src, dest)
        log(f"projects beside the exe: {dest}", "ok")
    except OSError as exc:
        log(f"projects not staged: {exc}", "error")


def stage_docs():
    """Copy the offline manual beside the executable in release bundles."""
    src = SRC / "docs"
    dest = DIST / "docs"
    if not src.is_dir():
        return
    try:
        shutil.copytree(src, dest, dirs_exist_ok=True)
        log(f"docs beside the exe: {dest}", "ok")
    except OSError as exc:
        log(f"docs not staged: {exc}", "error")


def stage_fonts():
    """Copy fonts beside the executable."""
    src = SRC / "fonts"
    dest = DIST / "fonts"
    if not src.is_dir() or dest.exists():
        return
    try:
        shutil.copytree(src, dest)
        log(f"fonts beside the exe: {dest}", "ok")
    except OSError as exc:
        log(f"fonts not staged: {exc}", "error")


def stage_app_ui():
    """Copy editor UI assets beside the executable."""
    src = SRC / "editor" / "appUI"
    dest = DIST / "editor" / "appUI"
    if not src.is_dir() or dest.exists():
        return
    try:
        shutil.copytree(src, dest, dirs_exist_ok=True)
        log(f"appUI beside the exe: {dest}", "ok")
    except OSError as exc:
        log(f"appUI not staged: {exc}", "error")


def stage_icon():
    """Copy the engine icon beside the executable for window/taskbar."""
    src = SRC / const.ICON_NAME
    if not src.is_file():
        return
    dest = DIST / const.ICON_NAME
    try:
        shutil.copy2(src, dest)
        log(f"icon beside the exe: {dest}", "ok")
    except OSError as exc:
        log(f"icon not staged: {exc}", "error")


# what a release carries: the app and the folders staged beside it
BUNDLE_FOLDERS = ("projects", "docs", "fonts", "editor")


def stage_bundle(target: Path, exe: Path):
    """Copy the finished app and its sidecars into one clean tree.

    Packing `dist/` straight would archive whatever else happens to live
    there - including the archive of the last run - and tar refuses to
    read a file it is busy writing. A staging tree ends both problems.
    """
    # copy2 keeps the mode, so a one-file binary stays executable inside a
    # tarball instead of needing a chmod after unpacking
    shutil.copy2(exe, target / exe.name)
    for folder in BUNDLE_FOLDERS:
        src = DIST / folder
        if src.is_dir():
            shutil.copytree(src, target / folder)
    icon = DIST / const.ICON_NAME
    if icon.is_file():
        shutil.copy2(icon, target / const.ICON_NAME)


def zip_bundle(source: Path, archive: Path):
    """A deflate zip of `source`, written by zipfile rather than by shell."""
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as zf:
        for file in sorted(source.rglob("*")):
            if file.is_file():
                zf.write(file, file.relative_to(source))


def pack_tools(cmd):
    """Run a packing tool, printing its words first if it refuses.

    `capture_output` hides the reason for a failed tar or ditto behind a
    bare CalledProcessError, which reads as a mystery in a CI log.
    """
    try:
        subprocess.run(cmd, check=True, capture_output=True, text=True)
    except subprocess.CalledProcessError as exc:
        for line in ((exc.stdout or "") + (exc.stderr or "")).splitlines():
            log(line, "error")
        raise


def pack_release():
    """Create the release archive for the current platform."""
    exe = exe_path()
    if not exe.is_file():
        log(f"expected exe missing: {exe}", "error")
        return None
    suffix = ("windows.zip" if IS_WINDOWS else
              "macos.zip" if IS_MACOS else "linux.tar.gz")
    archive = DIST / f"{ENGINE_NAME}-{suffix}"
    # a bundle unpacked from an archive carries only the modes the archive
    # recorded, so make sure the bit worth recording is set before staging
    ensure_executable(exe)
    with tempfile.TemporaryDirectory() as scratch:
        # the bundle and its archive are siblings: nothing archives a tree
        # that holds the archive being built
        root = Path(scratch) / "bundle"
        root.mkdir()
        stage_bundle(root, exe)
        local = Path(scratch) / archive.name
        if IS_WINDOWS:
            zip_bundle(root, local)
        elif IS_MACOS:
            pack_tools(["ditto", "-c", "-k", "--sequesterRsrc",
                        str(root), str(local)])
        else:
            pack_tools(["tar", "-czf", str(local), "-C", str(root), "."])
        shutil.copy2(local, archive)
    log(f"packed: {archive}", "ok")
    return archive


def ensure_executable(exe: Path):
    """PyInstaller sets the exec bit on POSIX, but a filesystem mounted
    noexec or a copy through a Windows drive can strip it; re-add it so
    `Popen([exe])` does not fail with PermissionError."""
    if IS_WINDOWS:
        return
    try:
        mode = exe.stat().st_mode
        exe.chmod(mode | 0o111)
    except OSError:
        pass


def launch(exe: Path, console: bool) -> int:
    """Run the freshly built app and stream its stdout in this terminal."""
    ensure_executable(exe)
    log(f"launching: {exe}")
    args = [str(exe)]
    env = os.environ.copy()
    # force line-buffered stdout inside the child so we see engine logs
    # in real time, not in 4 KiB blocks
    env.setdefault("PYTHONUNBUFFERED", "1")
    try:
        proc = subprocess.Popen(args, cwd=str(exe.parent), env=env,
                                stdout=subprocess.PIPE,
                                stderr=subprocess.STDOUT,
                                text=True, bufsize=1)
    except OSError as exc:
        log(f"could not start the built app: {exc}", "error")
        return 5
    if console:
        for line in proc.stdout:
            print(line.rstrip(), flush=True)
        proc.stdout.close()
    code = proc.wait()
    log(f"app exited with {code}", "ok" if code == 0 else "error")
    return code


# -------------------------------------------------------------------- main
def main(argv=None):
    args = list(sys.argv[1:] if argv is None else argv)
    console = "--console" in args
    no_run = "--no-run" in args or "--norun" in args
    t0 = time.time()

    log(f"platform {'windows' if IS_WINDOWS else ('macos' if IS_MACOS else 'linux')}")
    log(f"source   {SRC}")
    log(f"output   {DIST / ENGINE_NAME}")
    log(f"mode     {'console' if console else 'windowed'}")

    DIST.mkdir(parents=True, exist_ok=True)
    BUILD.mkdir(parents=True, exist_ok=True)
    entry = write_entry()
    log(f"entry    {entry}")

    cfg = make_config(console)
    for line in cfg.plan.lines():
        log(line)
    code = run_build(cfg, entry)
    if code != 0:
        return code

    exe = exe_path()
    if not exe.is_file():
        log(f"expected exe missing: {exe}", "error")
        return 3
    size_mb = exe.stat().st_size / (1024 * 1024)
    log(f"built    {exe} ({size_mb:.1f} MB) in {time.time() - t0:.1f}s", "ok")

    stage_projects()
    stage_docs()
    stage_fonts()
    stage_app_ui()
    stage_icon()
    pack_release()
    if no_run:
        return 0
    return launch(exe, console)


if __name__ == "__main__":
    sys.exit(main())
